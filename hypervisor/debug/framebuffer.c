struct color {
	uint8_t a;
	uint8_t r;
	uint8_t g;
	uint8_t b;
};

const struct color font_color = { .a = 0xffU, .r = 0xffU, .g = 0xffU, .b = 0xffU};
const struct color bg_color = { .a = 0U, .r = 0U, .g = 0U, .b = 0U};
static uint32_t default_font_pixel;
static uint32_t default_bg_pixel;

static bool fb_is_open = false;
static void *fb_addr = NULL;
static uint32_t fb_x;
static uint32_t fb_y;
static uint32_t fb_pitch;
static uint32_t fb_scan_line;
static struct multiboot_framebuffer_color fb_color;

#define CHAR_WIDTH		8U
#define CHAR_HEIGHT		8U
#define TEXT_LINE_HEIGHT	12U

#define DEFAULT_TEXT_X		0U
#define HEADER_TEXT_Y		0U
#define INFO_TEXT_Y		10U
static uint32_t default_text_y = HEADER_TEXT_Y;

static uint32_t fb_output_pixel(const struct color cl)
{
	return (((uint32_t)cl.r << fb_color.red_position) | ((uint32_t)cl.g << fb_color.green_position)
		| ((uint32_t)cl.b << fb_color.blue_position));
}

static void fb_output_char_pixels(unsigned char a, uint32_t x, uint32_t y,
				const uint32_t font_pixel, const uint32_t background_pixel)
{
	uint8_t cy, cx;
	uint8_t mask[8] = {128U, 64U, 32U, 16U, 8U, 4U, 2U, 1U};
	const unsigned char *ptr = &char_8x8_rom[0] + (a * 8U);
	uint32_t *base32 = (uint32_t *)fb_addr + (fb_scan_line * TEXT_LINE_HEIGHT * y ) + (x * CHAR_WIDTH);

	for (cy = 0U; cy < CHAR_HEIGHT; cy++) {
		for (cx = 0U; cx < CHAR_WIDTH; cx++) {
			if ((*ptr & mask[cx]) != 0U) {
				*base32++ = font_pixel;
			} else {
				*base32++ = background_pixel;
			}
		}

		ptr++;
		base32 += fb_scan_line - 8U;
	}
}

static void fb_clear_text_line(uint32_t y)
{
	uint32_t *base32 = (uint32_t *)fb_addr + (fb_scan_line * TEXT_LINE_HEIGHT * y);

	memset((void *)base32, 0x0U, fb_pitch * TEXT_LINE_HEIGHT);
}

void fb_output_char(char a)
{
	static uint32_t text_x = DEFAULT_TEXT_X;
	static uint32_t text_y = HEADER_TEXT_Y;

	stac();

	switch (a) {
	case '\n':
		text_y += 1U;
		text_x = DEFAULT_TEXT_X;
		fb_clear_text_line(text_y);
		break;
	case '\r':
		text_x = DEFAULT_TEXT_X;
		fb_clear_text_line(text_y);
		break;
	default:
		if ((text_y < INFO_TEXT_Y) && (default_text_y == INFO_TEXT_Y)) {
			text_y = INFO_TEXT_Y;
		}
		if (text_x == DEFAULT_TEXT_X) {
			fb_clear_text_line(text_y);
		}
		fb_output_char_pixels(a, text_x, text_y, default_font_pixel, default_bg_pixel);
		text_x ++;
		break;
	}
	clac();

	/* make sure next char has valid text_x & text_y */
	if (text_x >= (fb_x / CHAR_WIDTH)) {
		text_x = DEFAULT_TEXT_X;
		text_y += 1U;
	}
	text_y = (text_y >= (fb_y / TEXT_LINE_HEIGHT)) ? INFO_TEXT_Y : text_y;
}

void fb_outputs(const char *s, size_t len)
{
	const char *start = s;
	const char *end = s + len;

	while ((*start != '\0') && (start != end)) {
		fb_output_char(*start);
		start++;
	}
}

bool fb_need_log()
{
	if (fb_is_open) {
		return true;
	}
	return false;
}

void fb_log(char *buffer)
{
	uint64_t rflags;

	spinlock_irqsave_obtain(&framebuffer_log_lock ,&rflags);
	fb_outputs(buffer, strnlen_s(buffer, LOG_MESSAGE_MAX_SIZE));
	fb_outputs("\n", 1);
	spinlock_irqrestore_release(&framebuffer_log_lock, rflags);
}

void fb_init(bool early_boot)
{
	struct acrn_boot_info *abi = get_acrn_boot_info();
	uint64_t fb_end = 0UL;
	static bool is_fb_valid = false;

	/* Hv gets framebuffer's address, width, height, format through multiboot protocol */
	if (early_boot) {
		pr_info("ACRN Framebuffer info: <type: %d, addr: %lx, bpp: %d, width: %d, height: %d>\n",
			abi->framebuffer_info.type, abi->framebuffer_info.addr, abi->framebuffer_info.bpp,
			abi->framebuffer_info.width, abi->framebuffer_info.height);

		spinlock_init(&framebuffer_log_lock);
		/* Only 640x480+ Window with 32bpp ARGB format is supported */
		if ((abi->framebuffer_info.type == MULTIBOOT_FRAMEBUFFER_TYPE_RGB)
				&& (abi->framebuffer_info.addr > 0UL) && (abi->framebuffer_info.bpp == 32U)
				&& (abi->framebuffer_info.width >= 640U)
				&& (abi->framebuffer_info.height >= 480U)) {

			is_fb_valid = true;
			fb_x = abi->framebuffer_info.width;
			fb_y = abi->framebuffer_info.height;
			fb_pitch = abi->framebuffer_info.pitch;
			fb_scan_line = fb_pitch / 4U;
			fb_color = abi->framebuffer_color;
			default_font_pixel = fb_output_pixel(font_color);
			default_bg_pixel = fb_output_pixel(bg_color);
			if (abi->framebuffer_info.addr < MEM_4G) {
				fb_addr = hpa2hva_early(abi->framebuffer_info.addr);
				fb_end = (uint64_t)fb_addr + fb_y * fb_pitch;
				if (fb_end < MEM_4G) {
					memset(fb_addr, 0x0U, fb_y * fb_pitch);
					fb_is_open = true;
				}
			}
		}
	} else {
		if (is_fb_valid && (abi->framebuffer_info.addr > MEM_4G)) {
			fb_addr = hpa2hva(abi->framebuffer_info.addr);
			memset(fb_addr, 0x0U, fb_y * fb_pitch);
			fb_is_open = true;
		}
	}
}
