/**
 * @brief Global Boolean variable indicating if the L1D flush is required(false)
 * or not(true) when VM entry.
 *
 * According to the Intel SDM, 2.1 Vol.4:
 * SKIP_L1DFL_VMENTRY (bit3 of IA32_ARCH_CAPABILITIES): A value of 1 indicates the hypervisor
 * need not flush the L1D cache on VM entry.
 *
 * This global variable is true only if SKIP_L1DFL_VMENTRY bit is set.
 */
static bool skip_l1dfl_vmentry;

/**
 * @brief Global Boolean variable indicating if CPU internal buffer flush is required(true)
 * or not(false) when VM entry.
 *
 * This global variable is true only if MSR_IA32_ARCH_CAPABILITIES (10AH)[bit5=MDS_NO] is 0b and
 * CPUID.(EAX=7H, ECX=0):EDX[MD_CLEAR=10] is reports 1b and
 * 'skip_l1dfl_vmentry' is true.
 */
static bool cpu_md_clear;

/**
 * @brief Global variable indicating IBRS type.
 *
 * IBRS type can be IBRS_NONE, IBRS_RAW or IBRS_OPT depending on
 * hardware capability on underlying platform.
 */
static int32_t ibrs_type;


/**
 * @brief Detect IBRS type based on the hardware capability and configuration
 *        on underlying platform.
 *
 * This function determines the mitigation option for Spectre Variant 2
 * which is a branch target injection attack that target a CPU optimization
 * technique called speculation execution.
 *
 * Available Mitigations:
 *
 * IBRS (Indirect Branch Restricted Speculation): A hardware-level solution that
 *      restricts specculative execution on indirect branches.
 *
 * STIBP (Single Thread Indirect Branch Predictors): A hardware-level solution
 *       that restricts indirect branch prediction across different threads
 *       on the same core, preventing a thread from using speculative execution
 *       to attack another thread running on the same core.
 *
 * IBPB (Indirect Branch Predictor Barrier): A hardware-level solution that
 *      flushes the branch predictor of the CPU ensuring that an attacker can't
 *      leverage stale or maliciously injected values in the branch prediction
 *      buffers to launch Specture-style attack.
 *
 * Retpoline: A software mitigation introduced to prevent indirect branch prediction
 *            attacked by using a software-based mechanism to avoid speculation on
 *            indirect branches.
 *
 * Below mitigation options are defined for speculation defence:
 *
 * IBRS_RAW: Set IBRS at vmexit and then do IBPB at vcpu context switch (IBRS + IBPB).
 *
 * IBRS_OPT: An optimized method which set STIBP and do IBPB at vmexit, because having
 *           STIBP always set has less impact than having IBRS always set. Also since
 *           IBPB is already done at vmexit, it is no necessary to do so at vcpu context
 *           switch then (STIBP + IBPB).
 *
 * IBRS_NONE: Retpoline based software-only solution, which is an effective mitigation,
 *            especially for systems that can not implement more comprehensive hardware
 *            mitigations like IBRS or STIBP, this feature also can be enabled on platform
 *            that hardware-based mitigation is supported, because hardware-based mitigation
 *            has higher performance overhead, retpoline solution is a good balance between
 *            security and performance.
 *
 * @return None
 *
 * @pre N/A
 *
 * @post N/A
 *
 * @remark N/A
 */
static void detect_ibrs(void)
{
	ibrs_type = IBRS_NONE;

#ifndef CONFIG_RETPOLINE
	if (pcpu_has_cap(X86_FEATURE_IBRS_IBPB)) {
		ibrs_type = IBRS_RAW;
		if (pcpu_has_cap(X86_FEATURE_STIBP)) {
			ibrs_type = IBRS_OPT;
		}
	}
#endif
}

#ifdef CONFIG_RETPOLINE
/**
 * @brief Disable RRSBA (Restricted Return Stack Buffer Alternate) for underlying platform
 *
 * For platform that supports RRSBA (Restricted Return Stack Buffer Alternate),
 * using retpoline may not be sufficient to guard against branch history injection (BHI)
 * or Intra-mode branch target injection (IMBTI). RRSBA must be disabled to
 * prevent CPUs from using alternate predictors for RETs.
 *
 * Quoting Intel CVE-2022-0001/CVE-2022-0002 documentation:
 *
 * Where software is using retpoline as a mitigation for BHI or intra-mode BTI,
 * and the processor both enumerates RRSBA and enumerates RRSBA_DIS controls,
 * it should disable this behavior.
 * ...
 * Software using retpoline as a mitigation for BHI or intra-mode BTI should use
 * these new indirect predictor controls to disable alternate predictors for RETs.
 *
 * See: https://www.intel.com/content/www/us/en/developer/articles/technical/
 * software-security-guidance/technical-documentation/branch-history-injection.html
 *
 * @return None
 *
 * @pre N/A
 *
 * @post N/A
 *
 * @remark N/A.
 */
void disable_rrsba(void) {
	uint64_t v, x86_arch_caps;
	bool rrsba_behavior = false;

	x86_arch_caps = msr_read(MSR_IA32_ARCH_CAPABILITIES);
	rrsba_behavior = ((x86_arch_caps & IA32_ARCH_CAP_RESTRICTED_RSBA) != 0UL);

	if (rrsba_behavior && pcpu_has_cap(X86_FEATURE_RRSBA_CTRL)) {
		v = msr_read(MSR_IA32_SPEC_CTRL);
		/** Setting SPEC_RRSBA_DIS_S disables RRSBA behavior for CPL0/1/2 */
		v |= SPEC_RRSBA_DIS_S;
		msr_write(MSR_IA32_SPEC_CTRL, v);
	}
}
#endif

/**
 * @brief Return IBRS(Indirect Branch Restricted Speculation) type
 *
 * @return IBRS type
 *
 * @retval IBRS_NONE  Software-based solution (retpoline) support
 * @retval IBRS_RAW   Raw IBRS + IBPB speculation control support
 * @retval IBRS_OPT   With STIBP optimization speculation control support
 *
 * @pre N/A
 *
 * @post N/A
 *
 * @remark N/A
 */
int32_t get_ibrs_type(void)
{
	return ibrs_type;
}

/**
 * @brief Check the security system software interfaces for underlying platform
 *
 * Check if security system software interfaces are supported by physical platform for
 * known CPU vulnerabilities mitigation and return false if any of below
 * conditions is true, which means software interfaces are not sufficient
 * to mitigate specific known CPU vulnerability:
 *
 *   - MSR_IA32_ARCH_CAPABILITIES (10AH)[bit3=SKIP_L1DFL_VMENTRY] is 0b AND
 *     EDX bit 28(L1D_FLUSH) of CPUID.(EAX=7H,ECX=0H) reports 0b
 *
 *   - MSR_IA32_ARCH_CAPABILITIES (10AH)[bit4=SSB_NO] is 0b AND
 *     EDX bit 31(SSBD) of CPUID.(EAX=7H,ECX=0H) reports 0b
 *
 *   - MSR_IA32_ARCH_CAPABILITIES (10AH)[bit5=MDS_NO] is 0b AND
 *     EDX bit 10(MD_CLEAR) of CPUID.(EAX=7H,ECX=0H) reports 0b
 *
 *   - EDX bit 26(IBRS & IPBP) of CPUID.(EAX=7H,ECX=0H) reports 0b AND
 *     EDX bit 27(STIBP) of CPUID.(EAX=7H,ECX=0H) reports 0b
 *
 * This function also initializes skip_l1dfl_vmentry and cpu_md_clear based on
 * the system security capability.
 *
 * @return A Boolean value indicating whether software interfaces are sufficient to mitigate
 * known CPU vulnerabilities
 *
 * @retval true Software interfaces are sufficient to mitigate known CPU vulnerabilities

 * @retval false Software interfaces are not sufficient to mitigate known CPU vulnerabilities.
 *
 * @pre N/A
 *
 * @post N/A
 *
 * @remark CPU uCode shall be updated if this function returns false.
 */
bool check_cpu_security_cap(void)
{
	bool ret = true;
	/**
	 *  - Set mds_no to true only if IA32_ARCH_CAP_MDS_NO bit in MSR_IA32_ARCH_CAPABILITIES is set,
	 *   otherwise set it to false.
	 */
	bool mds_no = false;
	/**
	 *  - Set ssb_no to true only if IA32_ARCH_CAP_SSB_NO bit in MSR_IA32_ARCH_CAPABILITIES is set,
	 *   otherwise set it to false.
	 */
	bool ssb_no = false;

	uint64_t x86_arch_capabilities = 0UL;

	detect_ibrs();

	x86_arch_capabilities = msr_read(MSR_IA32_ARCH_CAPABILITIES);
	/** Set skip_l1dfl_vmentry to false if flushing L1D is required(false)
	 *  or true if flush L1D is not required on VM entry.
	 */
	skip_l1dfl_vmentry = ((x86_arch_capabilities & IA32_ARCH_CAP_SKIP_L1DFL_VMENTRY) != 0UL);

	/** Set mds_no to true if IA32_ARCH_CAP_MDS_NO bit in x86_arch_capabilities is set. */
	mds_no = ((x86_arch_capabilities & IA32_ARCH_CAP_MDS_NO) != 0UL);

	/** Set ssb_no to true if IA32_ARCH_CAP_SSB_NO bit in x86_arch_capabilities is set,
	 *  which means Processor is not susceptble to Speculative Store Bypass(SSB).
	 */
	ssb_no = ((x86_arch_capabilities & IA32_ARCH_CAP_SSB_NO) != 0UL);

	/** If L1D flush on VM entry is required, but L1D_FLUSH command is not
	 *  supported by physical platform.
	 */
	if ((!pcpu_has_cap(X86_FEATURE_L1D_FLUSH)) && (!skip_l1dfl_vmentry)) {
		/** Processor is affected by L1TF CPU vulnerability,
		 *  but no L1D_FLUSH command support,
		 *  Set the qualification of CPU ucode to false
		 */
		ret = false;
	}

	if ((!pcpu_has_cap(X86_FEATURE_SSBD)) && (!ssb_no)) {
		/** Processor is susceptble to Speculative Store Bypass(SSB),
		 *  but no support for Speculative Store Bypass Disable(SSBD),
		 *  Set the qualification of CPU ucode to false.
		 */
		ret = false;
	}

	if ((!pcpu_has_cap(X86_FEATURE_IBRS_IBPB)) && (!pcpu_has_cap(X86_FEATURE_STIBP))) {
		ret = false;
	}

	if (!mds_no) {
		if (pcpu_has_cap(X86_FEATURE_MDS_CLEAR)) {
			/** MSR_IA32_ARCH_CAPABILITIES is not supported by physical platform or
			 *  IA32_ARCH_CAP_MDS_NO bit in MSR_IA32_ARCH_CAPABILITIES is not set,
			 *  and MD_CLEAR is supported by physical platform.
			 *  In this case, set cpu_md_clear to true to indicate CPU internal buffers
			 *  flush shall be required on VM entry.
			 */
			cpu_md_clear = true;
#ifdef CONFIG_L1D_FLUSH_VMENTRY_ENABLED
			/** If the hypervisor need flush the L1D on VM entry */
			if (!skip_l1dfl_vmentry) {
				/** L1D cache flush will also overwrite CPU internal buffers,
				 *  additional MDS buffers clear operation is not required.
				 *  In this case, set cpu_md_clear to false to indicate CPU internal
				 *  buffers flush is not required on VM entry.
				 */
				cpu_md_clear = false;
			}
#endif
		} else {
			/** Processor is affected by MDS but no mitigation software
			 *  interface is enumerated, CPU microcode need to be updated.
			 *  Set the qualification of CPU ucode to false.
			 */
			ret = false;
		}
	}

	/** Return the qualification of CPU ucode */
	return ret;
}

#ifdef CONFIG_L1D_FLUSH_VMENTRY_ENABLED
 /**
  * @brief Flush L1 data cache if it is required on VM entry.
  *
  * This function flushes L1 data cache if such flush is required on VM entry(current processor is
  * potentially affected by L1TF CPU vulnerability).
  *
  *
  * @return None
  *
  * @pre N/A
  *
  * @post N/A
  */
void cpu_l1d_flush(void)
{
	/** If the hypervisor need flush the L1D on VM entry
	 *  'skip_l1dfl_vmentry' will be true on platform that
	 *  is not affected by L1TF.
	 */
	if (!skip_l1dfl_vmentry) {
		/** If L1D_FLUSH is supported by physical platform. */
		if (pcpu_has_cap(X86_FEATURE_L1D_FLUSH)) {
			/**
			 * Call msr_write() with the following parameters,
			 * in order to flush L1D cache.
			 *  - MSR_IA32_FLUSH_CMD
			 *  - IA32_L1D_FLUSH
			 */
			msr_write(MSR_IA32_FLUSH_CMD, IA32_L1D_FLUSH);
		}
	}

}

#endif

/**
 * @brief Overwrite CPU internal buffers with VERW instruction
 *
 * On processors that enumerate MD_CLEAR:CPUID.(EAX=7H,ECX=0):EDX[MD_CLEAR=10],
 * the VERW instruction or L1D_FLUSH command should be used to cause the
 * processor to overwrite buffer values that are affected by MDS
 * (Microarchitectural Data Sampling) vulnerabilities.
 *
 * The VERW instruction and L1D_FLUSH command will overwrite below buffer values:
 *  - Store buffer value for the current logical processor on processors affected
 *    by MSBDS (Microarchitectural Store Buffer Data Sampling).
 *  - Fill buffer for all logical processors on the physical core for processors
 *    affected by MFBDS (Microarchitectural Fill Buffer Data Sampling).
 *  - Load port for all logical processors on the physical core for processors
 *    affected by MLPDS(Microarchitectural Load Port Data Sampling).
 *
 * If processor is affected by L1TF vulnerability and the mitigation is enabled,
 * L1D_FLUSH will overwrite internal buffers on processors affected by MDS, no
 * additional buffer overwriting is required before VM entry. For other cases,
 * VERW instruction is used to overwrite buffer values for processors affected
 * by MDS.
 *
 * @return None
 *
 * @pre N/A
 *
 * @post N/A
 */
static inline void verw_buffer_overwriting(void)
{
	uint16_t ds = HOST_GDT_RING0_DATA_SEL;

	asm volatile ("verw %[ds]" : : [ds] "m" (ds) : "cc");
}

/**
 * @brief Clear CPU internal buffers.
 *
 * This function clears CPU internal buffers via VERW instruction
 * if it is required(current processor is potentially affected
 * by MDS CPU vulnerability).
 *
 * @return None
 *
 * @pre N/A
 *
 * @post N/A
 */
void cpu_internal_buffers_clear(void)
{
	/** If CPU internal buffers clearing is required */
	if (cpu_md_clear) {
		verw_buffer_overwriting();
	}
}

/**
 * @brief Get a random value
 *
 * Get a random number by executing rdrand instruction.
 *
 * @return a 64bit random number
 *
 * @pre N/A
 *
 * @post N/A
 */
uint64_t get_random_value(void)
{
	uint64_t random = 0UL;

	/** Execute rdrand in order to read a random number.
	 *  - Input operands: none
	 *  - Output operands: random
	 *  - Clobbers rax
	 */
	asm volatile ("1: rdrand %%rax\n"
			"jnc 1b\n"
			"mov %%rax, %0\n"
			: "=r"(random)
			:
			:"%rax");

	return random;
}

#ifdef STACK_PROTECTOR
/**
 * @brief Initialize the per-CPU stack canary structure for the current physical CPU
 *
 * Initialize the per-CPU stack canary structure for the current physical CPU by
 * assigning a random value to the canary. Also set the IA32_FS_BASE MSR of the current
 * physical CPU to the base address of the per-CPU stack canary structure.
 *
 * GCC generates extra code, using [fs:40] to access canary that is why
 * MSR_IA32_FS_BASE is used.
 *
 * @return None
 *
 * @pre N/A
 *
 * @post N/A
 */
void set_fs_base(void)
{
	int retry;
	/** Declare the following local variables of type struct stack_canary *.
	 *  - psc representing pointer to instance of struct stack_canary,
	 *  initialized as address of get_cpu_var(stk_canary).
	 */
	struct stack_canary *psc = &get_cpu_var(stk_canary);

	/**
	 *  1) Restore canary value on given pCPU if it has been configured.
	 *  2) Do retry in case 'get_random_value()' returns 0.
	 */
	for (retry = 0; (retry < 5) && (psc->canary == 0UL); retry++) {
		psc->canary = get_random_value();
	}

	if (psc->canary == 0UL) {
		panic("Failed to setup stack protector!");
	}
	msr_write(MSR_IA32_FS_BASE, (uint64_t)psc);
}
#endif
