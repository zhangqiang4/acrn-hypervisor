@dataclass
class TraceArgs:
    desc: str = ""
    enter_ts: int = 0
    exit_ts: int = 0
    rip: str = ""

    def to_dict(self):
        return asdict(self)

@dataclass
class TraceEvent:
    dur: str = ""
    name: str = "vmexit"
    ph: str = "X"
    pid: int = 1000000
    tid: int = 0
    ts: str = ""
    args: Optional[TraceArgs] = field(default_factory=TraceArgs)

    def to_dict(self):
        event_dict = asdict(self)
        event_dict['args'] = self.args.to_dict() if self.args else {}
        return event_dict

@dataclass
class ChromeTrace:
    traceEvents: List[TraceEvent]

    def to_dict(self):
        return {
            "traceEvents": [event.to_dict() for event in self.traceEvents]
        }

freq = 2400

def usage():
    print >> sys.stderr, \
          """
    Usage:
          trace.py [options] [formats] [trace_data] [output] [tsc_freq] [cpuid]

          [options]
          -h: print this message

          Parses trace_data in binary format generated by acrntrace,
          reformats it according to the rules in the [formats] file and converts
          it to JSON format for Chrome Trace Viewer.
          """

def read_format(format_file):
    formats = {}

    fd = open(format_file)

    reg = re.compile(r'(\S+)\s+(\S.*)')

    while True:
        line = fd.readline()
        if not line:
            break

        if line[0] == '#' or line[0] == '\n':
            continue

        m = reg.match(line)

        if not m: print >> sys.stderr, "Wrong format file"; sys.exit(1)

        formats[str(eval(m.group(1)))] = m.group(2)

    return formats

def parse_formats(formats):
    event_to_name = {}
    reg = re.compile(r'%\(tsc\)d\s+(.*?)\s+(\[|$)')
    for event, format in formats.items():
        m = reg.search(format)
        event_to_name[event] = m.group(1) if m else "Unknown"

    return event_to_name


exit = 0

# structure of trace data (as output by acrntrace)
# TSC(Q) HDR(Q) D1 D2 ...
# HDR consists of event:48:, n_data:8:, cpu:8:
# event means Event ID
# n_data means number of data in trace entry (like D1, D2, ...)
# cpu means cpu id this trace entry belong to
TSCREC = "Q"
HDRREC = "Q"
D2REC  = "QQ"
D4REC = "IIII"
D8REC = "BBBBBBBBBBBBBBBB"
D16REC = "bbbbbbbbbbbbbbbb"

def main_loop(chromtrace_obj, formats, event_to_name, fd, tsc_freq, cpuid):
    global exit
    i = 0

    while not exit:
        try:
            line = fd.read(struct.calcsize(TSCREC))
            if not line:
                break
            tsc = struct.unpack(TSCREC, line)[0]

            line = fd.read(struct.calcsize(HDRREC))
            if not line:
                break
            event = struct.unpack(HDRREC, line)[0]
            n_data = event >> 48 & 0xff
            cpu = event >> 56
            event = event & 0xffffffffffff

            d1 = 0
            d2 = 0
            d3 = 0
            d4 = 0
            d5 = 0
            d6 = 0
            d7 = 0
            d8 = 0
            d9 = 0
            d10 = 0
            d11 = 0
            d12 = 0
            d13 = 0
            d14 = 0
            d15 = 0
            d16 = 0

            if n_data == 2:
                line = fd.read(struct.calcsize(D2REC))
                if not line:
                    break
                (d1, d2) = struct.unpack(D2REC, line)

            if n_data == 4:
                line = fd.read(struct.calcsize(D4REC))
                if not line:
                    break
                (d1, d2, d3, d4) = struct.unpack(D4REC, line)

            if n_data == 8:
                line = fd.read(struct.calcsize(D8REC))
                if not line:
                    break
                # TRACE_6C using the first 6 data of fields_8. Actaully we have
                # 16 data in every trace entry.
                (d1, d2, d3, d4, d5, d6, d7, d8,
                 d9, d10, d11, d12, d13, d14, d15, d16) = struct.unpack(D8REC, line)

            if n_data == 16:
                line = fd.read(struct.calcsize(D16REC))
                if not line:
                    break

                (d1, d2, d3, d4, d5, d6, d7, d8,
                 d9, d10, d11, d12, d13, d14, d15, d16) = struct.unpack(D16REC, line)

            args = {'cpu'   : cpu,
                    'tsc'   : tsc,
                    'event' : event,
                    '1'     : d1,
                    '2'     : d2,
                    '3'     : d3,
                    '4'     : d4,
                    '5'     : d5,
                    '6'     : d6,
                    '7'     : d7,
                    '8'     : d8,
                    '9'     : d9,
                    '10'    : d10,
                    '11'    : d11,
                    '12'    : d12,
                    '13'    : d13,
                    '14'    : d14,
                    '15'    : d15,
                    '16'    : d16      }

            try:
                if str(event) in formats.keys():
                    if event == 0x10:
                        # vmexit
                        traceEvent = TraceEvent()
                        traceEvent.args.enter_ts = tsc

                    traceEvent.args.desc += formats[str(event)] % args + ";"

                    if event != 0x1 and event != 0x2 and event != 0x11 and event != 0x10:
                        #Ignore time add, time pick, vmenter, vmexit
                        traceEvent.name = event_to_name[str(event)]

                    if event == 0x11:
                        # vmenter
                        traceEvent.args.exit_ts = tsc
                        traceEvent.args.rip = d2

                        traceEvent.tid = traceEvent.pid + cpuid
                        # duration is in us
                        #traceEvent.dur = f"{(tsc - traceEvent.args.enter_ts) * 1e6 / tsc_freq:.6f}"
                        traceEvent.dur = (tsc - traceEvent.args.enter_ts) * 1e6 / tsc_freq

                        # tsc is in us
                        #traceEvent.ts = f"{tsc * 1e6 / tsc_freq:.6f}"
                        traceEvent.ts = tsc * 1e6 / tsc_freq
                        chromtrace_obj.traceEvents.append(traceEvent)


            except TypeError:
                if str(event) in formats.keys():
                    print(formats[str(event)])
                    print(args)
            except UnboundLocalError:
                pass

        except struct.error:
            sys.exit()

def main(argv):
    try:
        opts, arg = getopt.getopt(sys.argv[1:], "h")

        for opt in opts:
            if opt[0] == '-h':
                usage()
                sys.exit()

    except getopt.GetoptError:
        usage()
        sys.exit(1)

    try:
        formats = read_format(arg[0])
        event_to_name = parse_formats(formats)

        fd = open(arg[1], 'rb')
        output_filename = arg[2]
        tsc_freq = int(arg[3])
        cpuid = int(arg[4])
    except IOError:
        sys.exit(1)

    chrometrace_obj = ChromeTrace(traceEvents=[])
    main_loop(chrometrace_obj, formats, event_to_name, fd, tsc_freq, cpuid)

    with open(output_filename, 'w') as json_file:
        json.dump(chrometrace_obj.to_dict(), json_file, indent=4)

if __name__ == "__main__":
    main(sys.argv[1:])
